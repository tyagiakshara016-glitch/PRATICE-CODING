import java.util.*;
import java.lang.*;
import java.io.*;

class Codechef
{
	public static void main (String[] args) throws java.lang.Exception
	{
		Scanner sc = new Scanner(System.in);
		int N = sc.nextInt();
		int G = sc.nextInt();
		if(N>=G){
		    System.out.print("Yes");
		}
		else{
		    System.out.print("No");
		}

	}
}
